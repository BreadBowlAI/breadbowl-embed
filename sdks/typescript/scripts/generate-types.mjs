#!/usr/bin/env node
// Generates the TypeScript types and operation metadata from the public OpenAPI contract.
//
//   node scripts/generate-types.mjs          # write
//   node scripts/generate-types.mjs --check  # exit 1 if stale
//
// Outputs:
//   src/generated/openapi.ts  - openapi-typescript output (paths, components, operations)
//   src/generated/meta.ts     - operation table with x-error-codes, the x-error-details map,
//                               default server, spec hash
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '../..');
const specPath = resolve(repoRoot, 'sdks/openapi/bb-embed.v1.yaml');
const raw = readFileSync(specPath);
const sha256 = createHash('sha256').update(raw).digest('hex');
const spec = parse(raw.toString('utf8'));

const banner = `/**
 * GENERATED by scripts/generate-types.mjs from sdks/openapi/bb-embed.v1.yaml
 * (sha256 ${sha256}). Do not edit; run \`pnpm run generate\`.
 */
/* eslint-disable */
`;

const ast = await openapiTS(pathToFileURL(specPath), {
  // Request bodies must keep optional properties optional even when they have a default.
  defaultNonNullable: false,
  // Literal unions are enough; no runtime enums.
  enum: false,
});
const typesText = `${banner}\n${astToString(ast)}`;

// ------------------------------------------------------------------ metadata
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
function deref(node) {
  let cur = node;
  while (cur && cur.$ref) {
    cur = cur.$ref.replace(/^#\//, '').split('/').reduce((acc, k) => acc[k], spec);
  }
  return cur;
}
const operations = {};
for (const [path, item] of Object.entries(spec.paths)) {
  const shared = (item.parameters ?? []).map(deref);
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    const params = [...shared, ...(op.parameters ?? []).map(deref)];
    const security = op.security ?? spec.security ?? [];
    operations[op.operationId] = {
      method: method.toUpperCase(),
      path,
      authenticated: security.length > 0,
      scopes: security.flatMap((req) => Object.values(req).flat()),
      idempotencyKey: params.some((p) => p.in === 'header' && p.name === 'Idempotency-Key'),
      errorCodes: op['x-error-codes'] ?? {},
    };
  }
}
// Union of every operation's x-error-codes, per status.
const errorCodes = {};
for (const op of Object.values(operations)) {
  for (const [status, codes] of Object.entries(op.errorCodes)) {
    errorCodes[status] = [...new Set([...(errorCodes[status] ?? []), ...codes])];
  }
}
const errorDetails = spec.components.schemas.Error['x-error-details'] ?? {};
const server = spec.servers?.[0];
const serverUrl = server
  ? server.url.replace(/\{(\w+)\}/g, (_, name) => server.variables?.[name]?.default ?? '')
  : '';

const metaText = `${banner}
import type { components } from './openapi.js';

export const SPEC_VERSION = ${JSON.stringify(spec.info.version)};
export const SPEC_SHA256 = ${JSON.stringify(sha256)};
export const DEFAULT_BASE_URL = ${JSON.stringify(serverUrl)};

export interface OperationInfo {
  readonly method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
  readonly path: string;
  readonly authenticated: boolean;
  readonly scopes: readonly string[];
  readonly idempotencyKey: boolean;
  /** x-error-codes: the error codes this operation can return, per HTTP status. */
  readonly errorCodes: Readonly<Record<string, readonly string[]>>;
}

export const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const satisfies Record<string, OperationInfo>;

export type OperationId = keyof typeof OPERATIONS;

/** Error codes per HTTP status: the union of every operation's x-error-codes. */
export const ERROR_CODES = ${JSON.stringify(errorCodes, null, 2)} as const;

export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES][number];

/** x-error-details: error code -> name of the schema of its \`details\`. */
export const ERROR_DETAILS = ${JSON.stringify(errorDetails, null, 2)} as const;

/** The type of \`error.details\` for each code that has defined details. */
export interface ErrorDetailsByCode {
${Object.entries(errorDetails)
  .map(([code, schema]) => `  ${code}: components['schemas'][${JSON.stringify(schema)}];`)
  .join('\n')}
}
`;

const outputs = [
  [resolve(pkgRoot, 'src/generated/openapi.ts'), typesText],
  [resolve(pkgRoot, 'src/generated/meta.ts'), metaText],
];
const check = process.argv.includes('--check');
let stale = false;
for (const [file, text] of outputs) {
  let current = null;
  try {
    current = readFileSync(file, 'utf8');
  } catch {
    current = null;
  }
  if (current === text) continue;
  if (check) {
    console.error(`stale: ${relative(repoRoot, file)}`);
    stale = true;
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${relative(repoRoot, file)}`);
  }
}
if (stale) process.exit(1);
if (check) console.log('generated types up to date');
